-- Skema prototype Sistem Informasi Laundry Halilintar.
-- Tabel layanan/FAQ dapat dibaca chatbot publik; data pelanggan/pesanan hanya untuk server admin.

create extension if not exists pgcrypto;

create table if not exists public.services (
    id bigint generated by default as identity primary key,
    name text not null,
    description text not null default '',
    price_per_kg numeric(12, 2),
    price_per_piece numeric(12, 2),
    unit_type text not null default 'kg' check (unit_type in ('kg', 'potong')),
    estimated_hours integer,
    is_active boolean not null default true,
    created_at timestamptz not null default now()
);

alter table public.services add column if not exists price_per_piece numeric(12, 2);
alter table public.services add column if not exists unit_type text not null default 'kg';

create table if not exists public.faqs (
    id bigint generated by default as identity primary key,
    question text not null unique,
    answer text not null,
    is_active boolean not null default true,
    created_at timestamptz not null default now()
);

create table if not exists public.customers (
    id uuid primary key default gen_random_uuid(),
    name text not null check (length(trim(name)) between 1 and 120),
    phone text not null check (length(trim(phone)) between 8 and 24),
    auth_user_id uuid unique,
    email text,
    created_at timestamptz not null default now()
);

alter table public.customers add column if not exists auth_user_id uuid unique;
alter table public.customers add column if not exists email text;

create table if not exists public.orders (
    id uuid primary key default gen_random_uuid(),
    order_code text not null unique,
    customer_id uuid not null references public.customers(id) on delete restrict,
    service_id bigint not null references public.services(id) on delete restrict,
    weight_kg numeric(7, 2) not null check (weight_kg > 0),
    price_per_kg numeric(12, 2) not null check (price_per_kg >= 0),
    total_price numeric(12, 2) not null check (total_price >= 0),
    status text not null default 'Diterima'
        check (status in ('Diterima', 'Diproses', 'Siap Diambil', 'Selesai', 'Dibatalkan')),
    payment_method text
        check (payment_method is null or payment_method in ('Tunai', 'QRIS', 'Transfer Bank')),
    payment_status text not null default 'Belum Lunas'
        check (payment_status in ('Belum Lunas', 'Lunas')),
    received_at timestamptz not null default now(),
    estimated_ready_at timestamptz not null,
    notes text not null default '',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists orders_status_idx on public.orders(status);
create index if not exists orders_received_at_idx on public.orders(received_at desc);
create index if not exists orders_customer_id_idx on public.orders(customer_id);
create index if not exists orders_service_id_idx on public.orders(service_id);

alter table public.services enable row level security;
alter table public.faqs enable row level security;
alter table public.customers enable row level security;
alter table public.orders enable row level security;

drop policy if exists "Anyone can view active services" on public.services;
create policy "Anyone can view active services"
    on public.services for select to anon, authenticated using (is_active = true);
drop policy if exists "Anyone can view active FAQs" on public.faqs;
create policy "Anyone can view active FAQs"
    on public.faqs for select to anon, authenticated using (is_active = true);

revoke all on table public.services, public.faqs, public.customers, public.orders from anon, authenticated, public;
grant select on table public.services, public.faqs to anon, authenticated;
grant all on table public.customers, public.orders to service_role;

insert into public.services (name, description, price_per_kg, estimated_hours, unit_type, is_active)
select seed.name, seed.description, seed.price_per_kg, seed.estimated_hours, 'kg', true
from (values
    ('Cuci + Setrika Reguler', 'Cuci, kering, setrika, dan lipat. Estimasi 3 hari.', 7000::numeric, 72),
    ('Cuci + Lipat', 'Cuci, kering, dan lipat tanpa setrika. Estimasi 2 hari.', 6000::numeric, 48),
    ('Express Cuci + Setrika', 'Cuci, kering, setrika, dan lipat express. Estimasi 1 hari.', 14000::numeric, 24)
) as seed(name, description, price_per_kg, estimated_hours)
where not exists (select 1 from public.services existing where existing.name = seed.name);

